export const PLACEMENT_QUESTIONS = [...GRAMMAR_QUESTIONS, ...VOCABULARY_QUESTIONS, ...READING_QUESTIONS];

export function computePlacementTest(answers) {
  let score = 0;
  const total = PLACEMENT_QUESTIONS.length;
  const grammarTotal = GRAMMAR_QUESTIONS.length;
  const vocabularyTotal = VOCABULARY_QUESTIONS.length;
  const readingTotal = READING_QUESTIONS.length;
  let grammarScore = 0;
  let vocabularyScore = 0;
  let readingScore = 0;
  PLACEMENT_QUESTIONS.forEach((q) => {
    const correct = answers[q.id] === q.correctAnswer;
    if (correct) score++;
    if (q.skillArea === "grammar") grammarScore += +!!correct;
    else if (q.skillArea === "vocabulary") vocabularyScore += +!!correct;
    else if (q.skillArea === "reading") readingScore += +!!correct;
  });
  const pct = (score / total) * 100;
  const level = pct >= 90 ? "B2" : pct >= 70 ? "B1" : pct >= 45 ? "A2" : "A1";
  const weakAreas = [];
  if (grammarScore / grammarTotal < 0.6) weakAreas.push("grammar");
  if (vocabularyScore / vocabularyTotal < 0.6) weakAreas.push("vocabulary");
  if (readingScore / readingTotal < 0.6) weakAreas.push("reading");
  return {
    level,
    score,
    total,
    grammarScore,
    vocabularyScore,
    readingScore,
    weakAreas,
  };
}
